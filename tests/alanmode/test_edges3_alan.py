def test_modelled_s11(
    alanmode_modelled_s11s: QTable,
    legacy_modelled_s11s: QTable,
):
    alanfreq = legacy_modelled_s11s["freqs"]
    ourfreq = alanmode_modelled_s11s["freqs"]

    # Even though the legacy code ends up using modelled S11s only in the range
    # WFSTART to WFSTOP, the modelled S11s are actually generated across the full range
    # FSTART-FSTOP and written that way, so we need to mask them to compare
    mask = (alanfreq >= ourfreq.min()) & (alanfreq <= ourfreq.max())

    for key in alanmode_modelled_s11s.colnames:
        # Test that all values are good to 2e-5
        np.testing.assert_allclose(
            alanmode_modelled_s11s[key],
            legacy_modelled_s11s[key][mask],
            atol=2e-5,
            rtol=0,
            err_msg=f"Modelled S11 for {key}",
        )

        # Value not near the edges should be even better, at 2e-6
        np.testing.assert_allclose(
            alanmode_modelled_s11s[key][50:-50],
            legacy_modelled_s11s[key][mask][50:-50],
            atol=2e-6,
            rtol=0,
            err_msg=f"Modelled S11 for {key}",
        )


def test_specal(alanmode_specal: Calibrator, legacy_specal: Calibrator):
    np.testing.assert_allclose(legacy_specal.freqs, alanmode_specal.freqs)
    np.testing.assert_allclose(legacy_specal.Tsca, alanmode_specal.Tsca, rtol=3e-6)
    np.testing.assert_allclose(legacy_specal.Toff, alanmode_specal.Toff, atol=4e-5)
    np.testing.assert_allclose(legacy_specal.Tunc, alanmode_specal.Tunc, atol=1.1e-6)
    np.testing.assert_allclose(legacy_specal.Tcos, alanmode_specal.Tcos, atol=2e-5)
    np.testing.assert_allclose(legacy_specal.Tsin, alanmode_specal.Tsin, atol=2.2e-5)


def _matched_calibrated_temps(ours: dict, alan: np.ndarray) -> np.ndarray:
    """Cut Alan's calibrated temperatures to the frequencies we calibrate."""
    # Alan writes the calibrated temperatures on fstart-fstop, while we only calibrate
    # within wfstart-wfstop. Allow a tiny tolerance for the file's precision.
    mask = (alan["freq"] >= ours["freq"].min() - 1e-6) & (
        alan["freq"] <= ours["freq"].max() + 1e-6
    )
    alan = alan[mask]
    np.testing.assert_allclose(ours["freq"], alan["freq"], atol=1e-9, rtol=0)
    return alan


@pytest.mark.parametrize("key", am.LOADMAP.values())
def test_calibrated_temps(
    dataset: Dataset,
    alanmode_calibrated_temps: dict[str, dict[str, np.ndarray]],
    legacy_calibrated_temps: dict[str, np.ndarray],
    key: str,
):
    ours = alanmode_calibrated_temps[key]
    alan = _matched_calibrated_temps(ours, legacy_calibrated_temps[key])

    np.testing.assert_allclose(ours["uncal"], alan["uncal"], atol=1e-9, rtol=0)
    np.testing.assert_allclose(
        ours["cal"], alan["cal"], atol=dataset.calibrated_temp_atol[key], rtol=0
    )


@pytest.mark.xfail(
    strict=True,
    reason=(
        "Calibrated open/short temperatures differ from Alan's C code by up to "
        "~1.5 mK (2022_316, largest at the 50 MHz edge) and ~0.1-0.2 mK (2023_210), "
        "much more than the <0.1 mK agreement of the ambient and hot loads. The cause "
        "is not yet understood (issue #311)."
    ),
)
@pytest.mark.parametrize("key", ["open", "short"])
def test_calibrated_temps_open_short_tight(
    alanmode_calibrated_temps: dict[str, dict[str, np.ndarray]],
    legacy_calibrated_temps: dict[str, np.ndarray],
    key: str,
):
    ours = alanmode_calibrated_temps[key]
    alan = _matched_calibrated_temps(ours, legacy_calibrated_temps[key])

    # The same precision as the ambient load attains.
    np.testing.assert_allclose(ours["cal"], alan["cal"], atol=5e-5, rtol=0)


@pytest.mark.xfail(
    strict=True,
    reason=(
        "On hold pending a hardware check: CalibrationObservation."
        "from_edges3_caldef passes cable_loss_percent and cable_dielectric_percent "
        "as percent Quantities, which are converted to fractions twice (lossf 0.99085 "
        "instead of Alan's 0.085), and defaults the match resistance to 49.962 Ohm "
        "where alanmode and Alan's C code use 49.8 Ohm. Both are under review; fix "
        "pending (result-changing)."
    ),
)
def test_receiver_s11_matches_from_edges3_caldef(monkeypatch):
    """Cross-pipeline check: alanmode and edges.cal give the same receiver S11.

    The spectra (.acq files) for this day are not in the repo, so we cannot build the
    full CalibrationObservation. Instead we intercept ``_from_caldef`` to compute only
    the raw receiver reflection coefficient, exactly as ``_from_caldef`` does it, from
    the receiver options that ``from_edges3_caldef`` sets by default.
    """
    dataset = DATASETS["2022_316"]
    s11freq, raws11s = dataset.defparams.get_raw_s11s()

    def _raw_receiver_only(cls, caldef, *, receiver_kwargs=None, **kwargs):
        receiver_kwargs = dict(receiver_kwargs or {})
        receiver_kwargs.pop("model_params", None)
        return sp.get_gamma_receiver_from_filespec(caldef, **receiver_kwargs)

    monkeypatch.setattr(
        CalibrationObservation, "_from_caldef", classmethod(_raw_receiver_only)
    )
    raw_receiver = CalibrationObservation.from_edges3_caldef(
        dataset.defparams.get_caldef()
    )

    np.testing.assert_allclose(
        raw_receiver.freqs.to_value("MHz"), s11freq.to_value("MHz"), rtol=1e-12
    )
    np.testing.assert_allclose(
        raw_receiver.reflection_coefficient,
        raws11s["receiver_s11"],
        atol=1e-10,
        rtol=0,
    )
