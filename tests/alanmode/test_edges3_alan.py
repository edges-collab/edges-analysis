"""
Integration tests comparing EDGES-3 C-code outputs to alanmode functions.

Every test in this module runs for each of two calibration datasets:

* ``2022_316``: the original EDGES-3 test day.
* ``2023_210``: the set of observations used for the first EDGES-3 release.

Apart from the data files, the two datasets differ in:

* the assumed load temperatures;
* fstart/fstop in the calibration step. In 2022_316, fstart/fstop are only set
  for the acqplot7amoon step, and the fstart/fstop in edges() equal
  wfstart/wfstop. In 2023_210 they are different, which affects the S11 modelling.

Some tests in this module only run on enterprise, where the raw spectra are
available. Elsewhere, those tests are short-circuited by using the legacy averaged
spectra.

Legacy C-code outputs are in `tests/data/alanmode/edges3-<year>-<day>-alan/`.
S11 raw inputs are in `tests/data/alanmode/edges3-<year>-<day>-raw/` (spectra aren't
kept there because they are too big).

The legacy C-code outputs are generated by the code in
https://github.com/edges-collab/alans-pipeline. Specifically, from top-level, run:

```bash
make
cd scripts/edges3
./docal_edges3_<year>_<day>
cd ../..
cp results/edges3-<year>-<day>/* \
    <this_repo>/tests/data/alanmode/edges3-<year>-<day>-alan/
```
"""

