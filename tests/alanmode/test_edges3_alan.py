@pytest.fixture(scope="module")
def alanmode_calibrated_temps(
    dataset: Dataset, _alanmode_calibration
) -> dict[str, dict[str, np.ndarray]]:
    """Our calibrated temperatures, in the conventions of Alan's calibrated_*.txt.

    Alan's "uncal" column is the approximate temperature Q*tcal + tload (not Q), and
    his calibrated hot-load temperature is corrected for the hot-load cable loss,
    i.e. it is the temperature of the hot load itself, (T - (1-L) T_amb) / L, rather
    than the temperature at the receiver input.
    """
    calobs, calibrator, _ = _alanmode_calibration

    out = {}
    for loadname in am.LOADMAP.values():
        load = calobs.loads[loadname]
        uncal = load.averaged_q * dataset.acqparams.tcal + dataset.acqparams.tload
        cal = calibrator.calibrate_load(load).to_value("K")
        if loadname == "hot_load":
            loss = load.loss
            cal = (cal - (1 - loss) * dataset.calparams.tcold) / loss

        out[loadname] = {
            "freq": load.freqs.to_value("MHz"),
            "uncal": uncal,
            "cal": cal,
        }

    return out


